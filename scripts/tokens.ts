/**
 * Generates the web, iOS, and Android design tokens from `design/tokens.json`: `bun scripts/tokens.ts` writes
 * `public/tokens.css`, `ios/Golem/Design/Tokens.swift`, and `android/app/src/main/java/dev/golem/design/Tokens.kt`.
 */
import tokens from "../design/tokens.json" with { type: "json" };
import { LOGO_SIDES, logo } from "./icon.ts";

type Tokens = typeof tokens;
interface ShadowLayer {
  y: number;
  blur: number;
  spread: number;
  opacity: number;
}
interface Shadow {
  light: readonly ShadowLayer[];
  dark: readonly ShadowLayer[];
}

export const outputs = {
  "public/tokens.css": css,
  "ios/Golem/Design/Tokens.swift": swift,
  "android/app/src/main/java/dev/golem/design/Tokens.kt": kotlin,
  "web/ui/pixels.ts": webPixels,
  "ios/Golem/Design/PixelArt.swift": swiftPixels,
  "android/app/src/main/java/dev/golem/design/PixelArt.kt": kotlinPixels,
} as const;

if (import.meta.main) {
  for (const [path, render] of Object.entries(outputs)) {
    await Bun.write(path, render(tokens));
  }
}

export function css(t: Tokens): string {
  const lines = [
    ...Object.entries(t.color).map(
      ([name, c]) =>
        `--color-${kebab(name)}: light-dark(${c.light}, ${c.dark});`
    ),
    ...scale("font-size", t.fontSize, "px"),
    ...scale("font-weight", t.fontWeight, ""),
    ...scale("line-height", t.lineHeight, ""),
    ...scale("space", t.space, "px"),
    ...scale("radius", t.radius, "px"),
    ...scale("size", t.size, "px"),
    ...Object.entries(t.shadow).map(
      ([name, shadow]) => `--shadow-${name}: ${cssShadow(shadow)};`
    ),
    ...scale("duration", t.duration, "ms"),
    ...Object.entries(t.easing).map(
      ([name, curve]) =>
        `--easing-${kebab(name)}: cubic-bezier(${curve.join(", ")});`
    ),
  ];
  return `/* Generated by scripts/tokens.ts from design/tokens.json. Do not edit. */\n:root {\n\tcolor-scheme: light dark;\n${lines.map((line) => `\t${line}`).join("\n")}\n}\n`;
}

export function swift(t: Tokens): string {
  const weights: Record<number, string> = {
    400: ".regular",
    450: ".regular",
    500: ".medium",
    550: ".medium",
    600: ".semibold",
  };
  const enumOf = (name: string, members: string[]) =>
    `\tenum ${name} {\n${members.map((member) => `\t\t${member}`).join("\n")}\n\t}`;
  const numbers = (values: Record<string, number>) =>
    Object.entries(values).map(
      ([name, value]) => `static let ${name}: CGFloat = ${value}`
    );
  return `// Generated by scripts/tokens.ts from design/tokens.json. Do not edit.
import SwiftUI

enum Tokens {
${[
  enumOf(
    "Colors",
    Object.entries(t.color).map(
      ([name, c]) =>
        `static let ${name} = Color(light: "${c.light}", dark: "${c.dark}")`
    )
  ),
  enumOf("FontSize", numbers(t.fontSize)),
  enumOf(
    "FontWeight",
    Object.entries(t.fontWeight).map(
      ([name, value]) => `static let ${name}: Font.Weight = ${weights[value]}`
    )
  ),
  enumOf("LineHeight", numbers(t.lineHeight)),
  enumOf("Space", numbers(t.space)),
  enumOf("Radius", numbers(t.radius)),
  enumOf("Size", numbers(t.size)),
  `\t/// The iOS app's own values, measured from Linear's iOS app.\n\tenum Mobile {\n${[
    enumOf(
      "Colors",
      Object.entries(t.mobile.color).map(
        ([name, c]) =>
          `static let ${name} = Color(light: "${c.light}", dark: "${c.dark}")`
      )
    ),
    enumOf("FontSize", numbers(t.mobile.fontSize)),
    enumOf("Size", numbers(t.mobile.size)),
  ]
    .join("\n\n")
    .replace(/^(?=.)/gm, "\t")}\n\t}`,
  enumOf(
    "Shadows",
    Object.entries(t.shadow).map(
      ([name, shadow]) =>
        `static let ${name}: [Shadow] = [${themedLayers(shadow)
          .map(
            ({ layer, light, dark }) =>
              `Shadow(y: ${layer.y}, blur: ${layer.blur}, color: Color(light: "${light}", dark: "${dark}"))`
          )
          .join(", ")}]`
    )
  ),
  enumOf(
    "Duration",
    Object.entries(t.duration).map(
      ([name, ms]) => `static let ${name}: Double = ${ms / 1000}`
    )
  ),
  enumOf(
    "Easing",
    Object.entries(t.easing).map(
      ([name, [x1, y1, x2, y2]]) =>
        `static func ${name}(_ duration: Double) -> Animation { .timingCurve(${x1}, ${y1}, ${x2}, ${y2}, duration: duration) }`
    )
  ),
].join("\n\n")}
}
`;
}

export function kotlin(t: Tokens): string {
  const palette = (
    name: string,
    colors: Record<string, { light: string; dark: string }>
  ) => {
    const fields = Object.keys(colors).map((key) => `\tval ${key}: Color,`);
    const instance = (theme: "light" | "dark") =>
      `val ${theme === "light" ? "Light" : "Dark"}${name} = ${name}(\n${Object.entries(
        colors
      )
        .map(([key, c]) => `\t${key} = ${kotlinColor(c[theme])},`)
        .join("\n")}\n)`;
    return `@Immutable\nclass ${name}(\n${fields.join("\n")}\n)\n\n${instance("light")}\n\n${instance("dark")}`;
  };
  const objectOf = (name: string, members: string[]) =>
    `\tobject ${name} {\n${members.map((member) => `\t\t${member}`).join("\n")}\n\t}`;
  const units = (values: Record<string, number>, unit: "dp" | "sp") =>
    Object.entries(values).map(
      ([name, value]) => `val ${name} = ${kotlinNumber(value)}.${unit}`
    );
  const layers = (list: readonly ShadowLayer[]) =>
    `listOf(${list
      .map(
        (layer) =>
          `ShadowLayer(y = ${kotlinNumber(layer.y)}.dp, blur = ${kotlinNumber(layer.blur)}.dp, spread = ${kotlinNumber(layer.spread)}.dp, alpha = ${layer.opacity}f)`
      )
      .join(", ")})`;
  return `// Generated by scripts/tokens.ts from design/tokens.json. Do not edit.
package dev.golem.design

import androidx.compose.animation.core.CubicBezierEasing
import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

${palette("Colors", t.color)}

${palette("MobileColors", t.mobile.color)}

/** One layer of a shadow: black at \`alpha\`. */
class ShadowLayer(val y: Dp, val blur: Dp, val spread: Dp, val alpha: Float)

/** A shadow's layers in each theme. */
class ThemedShadow(val light: List<ShadowLayer>, val dark: List<ShadowLayer>)

object Tokens {
${[
  objectOf("FontSize", units(t.fontSize, "sp")),
  objectOf(
    "FontWeight",
    Object.entries(t.fontWeight).map(
      ([name, value]) =>
        `val ${name} = androidx.compose.ui.text.font.FontWeight(${value})`
    )
  ),
  objectOf(
    "LineHeight",
    Object.entries(t.lineHeight).map(
      ([name, value]) => `const val ${name} = ${value}f`
    )
  ),
  objectOf("Space", units(t.space, "dp")),
  objectOf("Radius", units(t.radius, "dp")),
  objectOf("Size", units(t.size, "dp")),
  `\t/** The phone app's own values, measured from Linear's mobile apps. */\n\tobject Mobile {\n${[
    objectOf("FontSize", units(t.mobile.fontSize, "sp")),
    objectOf("Size", units(t.mobile.size, "dp")),
  ]
    .join("\n\n")
    .replace(/^(?=.)/gm, "\t")}\n\t}`,
  objectOf(
    "Shadows",
    Object.entries(t.shadow).map(
      ([name, shadow]) =>
        `val ${name} = ThemedShadow(light = ${layers(shadow.light)}, dark = ${layers(shadow.dark)})`
    )
  ),
  objectOf(
    "Duration",
    Object.entries(t.duration).map(([name, ms]) => `const val ${name} = ${ms}`)
  ),
  objectOf(
    "Easing",
    Object.entries(t.easing).map(
      ([name, curve]) =>
        `val ${name} = CubicBezierEasing(${curve.map((value) => `${value}f`).join(", ")})`
    )
  ),
].join("\n\n")}
}
`.replace(/\t/g, "    ");
}

/** The icons of `design/tokens.json` as SVG paths for the web app. */
export function webPixels(t: Tokens): string {
  // As Biome wraps them.
  const lines = Object.entries(t.icon).map(([name, art]) => {
    const line = `  ${name}: "${iconPath(name, art)}",`;
    return line.length > 80
      ? `  ${name}:\n    "${iconPath(name, art)}",`
      : line;
  });
  const letters = Object.entries(t.letter).map(
    ([letter, columns]) => `  "${letter}": "${letterPath(columns)}",`
  );
  return `// Generated by scripts/tokens.ts from design/tokens.json. Do not edit.\nexport const pixels = {\n${lines.join("\n")}\n} as const;\n\n/** Each letter of a person's tile, in a 12 × 12 grid. */\nexport const letters: Record<string, string> = {\n${letters.join("\n")}\n};\n`;
}

/** The same icons for iOS: each case's value is the path that `PixelShape` draws. */
export function swiftPixels(t: Tokens): string {
  const cases = Object.entries(t.icon).map(
    ([name, art]) => `    case ${name} = "${iconPath(name, art)}"`
  );
  const letters = Object.entries(t.letter).map(
    ([letter, columns]) => `    "${letter}": "${letterPath(columns)}",`
  );
  return `// Generated by scripts/tokens.ts from design/tokens.json. Do not edit.\nnonisolated enum Pixel: String {\n${cases.join("\n")}\n}\n\n/// Each letter of a person's tile, in a 12 × 12 grid.\nnonisolated let pixelLetters: [Character: String] = [\n${letters.join("\n")}\n]\n\n/// Golem's logo at each side in points: the paths of the face and the forehead mark, 1 pt a cell.\nnonisolated let golemLogos: [Int: (face: String, forehead: String)] = [\n${LOGO_SIDES.map((side) => `    ${side}: (face: "${logo(side).face}", forehead: "${logo(side).forehead}"),`).join("\n")}\n]\n`;
}

/** The same icons for Android, for \`pixelPath\`. */
export function kotlinPixels(t: Tokens): string {
  const entries = Object.entries(t.icon).map(
    ([name, art]) => `    ${pascal(name)}("${iconPath(name, art)}"),`
  );
  const letters = Object.entries(t.letter).map(
    ([letter, columns]) => `    '${letter}' to "${letterPath(columns)}",`
  );
  return `// Generated by scripts/tokens.ts from design/tokens.json. Do not edit.\npackage dev.golem.design\n\nenum class Pixel(val path: String) {\n${entries.join("\n")}\n}\n\n/** Each letter of a person's tile, in a 12 × 12 grid. */\nval pixelLetters: Map<Char, String> = mapOf(\n${letters.join("\n")}\n)\n\n/** Golem's logo at each side in dp: the paths of the face and the forehead mark, 1 dp a cell. */\nval golemLogos: Map<Int, Pair<String, String>> = mapOf(\n${LOGO_SIDES.map((side) => `    ${side} to ("${logo(side).face}" to "${logo(side).forehead}"),`).join("\n")}\n)\n`;
}

/** An icon's path; `golem` is the dissolving logo in one color. */
function iconPath(name: string, art: string): string {
  return name === "golem" ? logo(16, 0).face : pixelPath(art);
}

/** Rows of `#` and `.` as absolute `M`, `H`, `V`, and `Z` commands, one rectangle for each run in a row. */
function pixelPath(art: string): string {
  return art
    .split("|")
    .flatMap((row, y) =>
      [...row.matchAll(/#+/g)].map(
        (run) =>
          `M${run.index} ${y}H${run.index + run[0].length}V${y + 1}H${run.index}Z`
      )
    )
    .join("");
}

/** Five columns of seven bits, placed in the middle of a 12 × 12 grid. */
function letterPath(columns: string): string {
  let path = "";
  for (let column = 0; column < 5; column += 1) {
    const bits = Number.parseInt(columns.slice(column * 2, column * 2 + 2), 16);
    for (let row = 0; row < 7; row += 1) {
      if (Math.floor(bits / 2 ** row) % 2 === 1) {
        const x = 3 + column;
        path += `M${x} ${2 + row}H${x + 1}V${3 + row}H${x}Z`;
      }
    }
  }
  return path;
}

function pascal(name: string): string {
  return name.charAt(0).toUpperCase() + name.slice(1);
}

/** `#rrggbb` or `#rrggbbaa` as Kotlin's `Color(0xAARRGGBB)`. */
function kotlinColor(hex: string): string {
  const alpha = hex.length === 9 ? hex.slice(7, 9) : "ff";
  return `Color(0x${(alpha + hex.slice(1, 7)).toUpperCase()})`;
}

/** A whole number stays whole; a fraction gets the `f` that Kotlin's Float needs. */
function kotlinNumber(value: number): string {
  return Number.isInteger(value) ? `${value}` : `${value}f`;
}

function scale(
  prefix: string,
  values: Record<string, number>,
  unit: string
): string[] {
  return Object.entries(values).map(
    ([name, value]) => `--${prefix}-${kebab(name)}: ${value}${unit};`
  );
}

function cssShadow(shadow: Shadow): string {
  return themedLayers(shadow)
    .map(
      ({ layer, light, dark }) =>
        `0 ${layer.y}px ${layer.blur}px ${layer.spread}px light-dark(${light}, ${dark})`
    )
    .join(", ");
}

/** The light layers, then the dark ones; each layer is transparent in the other theme. */
function themedLayers(
  shadow: Shadow
): { layer: ShadowLayer; light: string; dark: string }[] {
  const none = "#00000000";
  return [
    ...shadow.light.map((layer) => ({
      layer,
      light: black(layer),
      dark: none,
    })),
    ...shadow.dark.map((layer) => ({ layer, light: none, dark: black(layer) })),
  ];
}

function black(layer: ShadowLayer): string {
  const alpha = Math.round(layer.opacity * 255);
  return `#000000${alpha.toString(16).padStart(2, "0")}`;
}

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

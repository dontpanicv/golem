/**
 * Generates the web and iOS design tokens from `design/tokens.json`:
 * `bun scripts/tokens.ts` writes `public/tokens.css` and `ios/Golem/Design/Tokens.swift`.
 */
import tokens from "../design/tokens.json";

type Tokens = typeof tokens;
type Shadow = readonly { y: number; blur: number; spread: number; opacity: number }[];

export const outputs = {
	"public/tokens.css": css,
	"ios/Golem/Design/Tokens.swift": swift,
} as const;

if (import.meta.main) {
	for (const [path, render] of Object.entries(outputs)) await Bun.write(path, render(tokens));
}

export function css(t: Tokens): string {
	const lines = [
		...Object.entries(t.color).map(([name, c]) => `--color-${kebab(name)}: light-dark(${c.light}, ${c.dark});`),
		...scale("font-size", t.fontSize, "px"),
		...scale("font-weight", t.fontWeight, ""),
		...scale("line-height", t.lineHeight, ""),
		...scale("space", t.space, "px"),
		...scale("radius", t.radius, "px"),
		...scale("size", t.size, "px"),
		...Object.entries(t.shadow).map(([name, layers]) => `--shadow-${name}: ${cssShadow(layers)};`),
		...scale("duration", t.duration, "ms"),
		...Object.entries(t.easing).map(([name, curve]) => `--easing-${kebab(name)}: cubic-bezier(${curve.join(", ")});`),
	];
	return `/* Generated by scripts/tokens.ts from design/tokens.json. Do not edit. */\n:root {\n\tcolor-scheme: light dark;\n${lines.map((line) => `\t${line}`).join("\n")}\n}\n`;
}

export function swift(t: Tokens): string {
	const weights: Record<number, string> = { 400: ".regular", 450: ".regular", 500: ".medium", 600: ".semibold" };
	const enumOf = (name: string, members: string[]) =>
		`\tenum ${name} {\n${members.map((member) => `\t\t${member}`).join("\n")}\n\t}`;
	const numbers = (values: Record<string, number>) =>
		Object.entries(values).map(([name, value]) => `static let ${name}: CGFloat = ${value}`);
	return `// Generated by scripts/tokens.ts from design/tokens.json. Do not edit.
import SwiftUI

enum Tokens {
${[
	enumOf(
		"Colors",
		Object.entries(t.color).map(([name, c]) => `static let ${name} = Color(light: "${c.light}", dark: "${c.dark}")`),
	),
	enumOf("FontSize", numbers(t.fontSize)),
	enumOf(
		"FontWeight",
		Object.entries(t.fontWeight).map(([name, value]) => `static let ${name}: Font.Weight = ${weights[value]}`),
	),
	enumOf("LineHeight", numbers(t.lineHeight)),
	enumOf("Space", numbers(t.space)),
	enumOf("Radius", numbers(t.radius)),
	enumOf("Size", numbers(t.size)),
	enumOf(
		"Shadows",
		Object.entries(t.shadow).map(
			([name, layers]) =>
				`static let ${name}: [Shadow] = [${(layers as Shadow).map((s) => `Shadow(y: ${s.y}, blur: ${s.blur}, opacity: ${s.opacity})`).join(", ")}]`,
		),
	),
	enumOf(
		"Duration",
		Object.entries(t.duration).map(([name, ms]) => `static let ${name}: Double = ${ms / 1000}`),
	),
	enumOf(
		"Easing",
		Object.entries(t.easing).map(
			([name, [x1, y1, x2, y2]]) =>
				`static func ${name}(_ duration: Double) -> Animation { .timingCurve(${x1}, ${y1}, ${x2}, ${y2}, duration: duration) }`,
		),
	),
].join("\n\n")}
}
`;
}

function scale(prefix: string, values: Record<string, number>, unit: string): string[] {
	return Object.entries(values).map(([name, value]) => `--${prefix}-${kebab(name)}: ${value}${unit};`);
}

function cssShadow(layers: Shadow): string {
	return layers.map((s) => `0 ${s.y}px ${s.blur}px ${s.spread}px rgb(0 0 0 / ${s.opacity})`).join(", ");
}

function kebab(name: string): string {
	return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

/**
 * Generates the web and iOS design tokens from `design/tokens.json`:
 * `bun scripts/tokens.ts` writes `public/tokens.css` and `ios/Golem/Design/Tokens.swift`.
 */
import tokens from "../design/tokens.json" with { type: "json" };

type Tokens = typeof tokens;
interface ShadowLayer {
  y: number;
  blur: number;
  spread: number;
  opacity: number;
}
interface Shadow {
  light: readonly ShadowLayer[];
  dark: readonly ShadowLayer[];
}

export const outputs = {
  "public/tokens.css": css,
  "ios/Golem/Design/Tokens.swift": swift,
} as const;

if (import.meta.main) {
  for (const [path, render] of Object.entries(outputs)) {
    await Bun.write(path, render(tokens));
  }
}

export function css(t: Tokens): string {
  const lines = [
    ...Object.entries(t.color).map(
      ([name, c]) =>
        `--color-${kebab(name)}: light-dark(${c.light}, ${c.dark});`
    ),
    ...t.avatar.map((color, index) => `--avatar-${index}: ${color};`),
    ...scale("font-size", t.fontSize, "px"),
    ...scale("font-weight", t.fontWeight, ""),
    ...scale("line-height", t.lineHeight, ""),
    ...scale("space", t.space, "px"),
    ...scale("radius", t.radius, "px"),
    ...scale("size", t.size, "px"),
    ...Object.entries(t.shadow).map(
      ([name, shadow]) => `--shadow-${name}: ${cssShadow(shadow)};`
    ),
    ...scale("duration", t.duration, "ms"),
    ...Object.entries(t.easing).map(
      ([name, curve]) =>
        `--easing-${kebab(name)}: cubic-bezier(${curve.join(", ")});`
    ),
  ];
  return `/* Generated by scripts/tokens.ts from design/tokens.json. Do not edit. */\n:root {\n\tcolor-scheme: light dark;\n${lines.map((line) => `\t${line}`).join("\n")}\n}\n`;
}

export function swift(t: Tokens): string {
  const weights: Record<number, string> = {
    400: ".regular",
    450: ".regular",
    500: ".medium",
    550: ".medium",
    600: ".semibold",
  };
  const enumOf = (name: string, members: string[]) =>
    `\tenum ${name} {\n${members.map((member) => `\t\t${member}`).join("\n")}\n\t}`;
  const numbers = (values: Record<string, number>) =>
    Object.entries(values).map(
      ([name, value]) => `static let ${name}: CGFloat = ${value}`
    );
  return `// Generated by scripts/tokens.ts from design/tokens.json. Do not edit.
import SwiftUI

enum Tokens {
${[
  enumOf(
    "Colors",
    Object.entries(t.color).map(
      ([name, c]) =>
        `static let ${name} = Color(light: "${c.light}", dark: "${c.dark}")`
    )
  ),
  `\tstatic let avatarColors: [Color] = [${t.avatar.map((color) => `Color(light: "${color}", dark: "${color}")`).join(", ")}]`,
  enumOf("FontSize", numbers(t.fontSize)),
  enumOf(
    "FontWeight",
    Object.entries(t.fontWeight).map(
      ([name, value]) => `static let ${name}: Font.Weight = ${weights[value]}`
    )
  ),
  enumOf("LineHeight", numbers(t.lineHeight)),
  enumOf("Space", numbers(t.space)),
  enumOf("Radius", numbers(t.radius)),
  enumOf("Size", numbers(t.size)),
  `\t/// The iOS app's own values, measured from Linear's iOS app.\n\tenum Mobile {\n${[
    enumOf(
      "Colors",
      Object.entries(t.mobile.color).map(
        ([name, c]) =>
          `static let ${name} = Color(light: "${c.light}", dark: "${c.dark}")`
      )
    ),
    enumOf("FontSize", numbers(t.mobile.fontSize)),
    enumOf("Size", numbers(t.mobile.size)),
  ]
    .join("\n\n")
    .replace(/^(?=.)/gm, "\t")}\n\t}`,
  enumOf(
    "Shadows",
    Object.entries(t.shadow).map(
      ([name, shadow]) =>
        `static let ${name}: [Shadow] = [${themedLayers(shadow)
          .map(
            ({ layer, light, dark }) =>
              `Shadow(y: ${layer.y}, blur: ${layer.blur}, color: Color(light: "${light}", dark: "${dark}"))`
          )
          .join(", ")}]`
    )
  ),
  enumOf(
    "Duration",
    Object.entries(t.duration).map(
      ([name, ms]) => `static let ${name}: Double = ${ms / 1000}`
    )
  ),
  enumOf(
    "Easing",
    Object.entries(t.easing).map(
      ([name, [x1, y1, x2, y2]]) =>
        `static func ${name}(_ duration: Double) -> Animation { .timingCurve(${x1}, ${y1}, ${x2}, ${y2}, duration: duration) }`
    )
  ),
].join("\n\n")}
}
`;
}

function scale(
  prefix: string,
  values: Record<string, number>,
  unit: string
): string[] {
  return Object.entries(values).map(
    ([name, value]) => `--${prefix}-${kebab(name)}: ${value}${unit};`
  );
}

function cssShadow(shadow: Shadow): string {
  return themedLayers(shadow)
    .map(
      ({ layer, light, dark }) =>
        `0 ${layer.y}px ${layer.blur}px ${layer.spread}px light-dark(${light}, ${dark})`
    )
    .join(", ");
}

/** The light layers, then the dark ones; each layer is transparent in the other theme. */
function themedLayers(
  shadow: Shadow
): { layer: ShadowLayer; light: string; dark: string }[] {
  const none = "#00000000";
  return [
    ...shadow.light.map((layer) => ({
      layer,
      light: black(layer),
      dark: none,
    })),
    ...shadow.dark.map((layer) => ({ layer, light: none, dark: black(layer) })),
  ];
}

function black(layer: ShadowLayer): string {
  const alpha = Math.round(layer.opacity * 255);
  return `#000000${alpha.toString(16).padStart(2, "0")}`;
}

function kebab(name: string): string {
  return name.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}
